DOT2 = ("##", "##")
DOT4 = (".##.", "####", "####", ".##.")


def render(symbol, pitch, dot):
    s = len(dot)
    cell_w = 6 * pitch
    cell_h = 9 * pitch - s
    stride = (cell_w + 7) // 8

    bitmap = bytearray()
    for code in range(0x20, 0x7F):
        grid = G[chr(code)]
        cell = [bytearray(stride) for _ in range(cell_h)]
        for gy in range(8):
            for gx in range(5):
                if grid[gy][gx] != '#':
                    continue
                for dy in range(s):
                    for dx in range(s):
                        if dot[dy][dx] != '#':
                            continue
                        x = gx * pitch + dx
                        y = gy * pitch + dy
                        cell[y][x >> 3] |= 0x80 >> (x & 7)
        for row in cell:
            bitmap.extend(row)

    name = f"{symbol}_{cell_w}x{cell_h}"
    out = []
    out.append("#include <stdint.h>")
    out.append('#include "gfx.h"')
    out.append("")
    out.append(f"static const uint8_t {name}_data[{len(bitmap)}] = {{")
    for i in range(0, len(bitmap), 12):
        chunk = bitmap[i : i + 12]
        out.append("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
    out.append("};")
    out.append("")
    out.append(f"const gfx_font_t {name} = {{")
    out.append(f"    .w     = {cell_w},")
    out.append(f"    .h     = {cell_h},")
    out.append("    .first = 0x20,")
    out.append("    .last  = 0x7E,")
    out.append(f"    .bitmap = {name}_data,")
    out.append("};")
    return name, "\n".join(out)


if __name__ == "__main__":
    assert len(G) == 95
    for ch, rows in G.items():
        assert len(rows) == 8 and all(len(r) == 5 for r in rows), repr(ch)

    import os
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    for pitch, dot in ((3, DOT2), (5, DOT4)):
        name, src = render("gfx_font_dots", pitch, dot)
        path = os.path.join(here, "src", f"font_{name.removeprefix('gfx_font_')}.c")
        with open(path, "w") as f:
            f.write(src + "\n")
        print(name, "->", path)
